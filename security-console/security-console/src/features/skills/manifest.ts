/**
 * manifest.ts — AI 技能清单文档（Manifest）
 *
 * 这份文档会被永远注入到 AI 系统提示中（system_extra 的一部分）。
 * 它告知 AI：
 *   - 自己具备哪些可调用的技能工具
 *   - 每种技能的用途和调用语法摘要
 *   - 通用的调用协议规则
 *
 * 设计原则：
 *   - 紧凑：只写必要信息，减少 token 消耗
 *   - 完整：每个技能必须有调用语法，AI 不需要记忆
 *   - 可扩展：新增技能时，在 SKILLS_TABLE 追加一行即可
 *
 * 注意：每个技能的详细约定（参数说明、示例、错误处理）
 * 存放在 contracts/ 目录下，由 buildSystemPrompt() 按需注入。
 */

