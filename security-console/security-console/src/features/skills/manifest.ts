const SKILLS_TABLE = `
| 技能名称 | 用途 | 调用语法 |
|---------|------|---------|
| Terminal_control | 在受控端执行 Shell 命令并获取输出 | \`<Terminal_control>{"cmd":"命令","timeout":秒数}</Terminal_control>\` |
`.trim();

// ─── 调用协议规则 ─────────────────────────────────────────────────────────────

const CALLING_PROTOCOL = `
## 技能调用协议

### 调用规则（必须严格遵守）
1. **完整标签**：技能标签必须完整闭合，payload 必须是有效 JSON
2. **单次调用**：一条回复中只插入一个技能标签，插入后立即停止输出，等待执行结果
3. **等待结果**：系统会自动执行并在消息中注入 [执行结果]，收到后再继续分析
4. **结果驱动**：基于实际执行结果进行分析，不要猜测或假设输出内容
5. **异常处理**：若结果含错误或超时，应说明原因并给出替代方案

### 何时使用技能
- 需要获取目标机器的实时状态时（进程列表、网络连接、文件内容等）
- 需要验证安全假设时（确认恶意文件是否存在、确认持久化机制等）
- 需要收集 IOC 证据时（哈希值、注册表值、网络连接等）
- **不要**在已有充足上下文信息时调用技能，避免不必要的命令执行

### 调用示例
\`\`\`
我需要查看该进程的网络连接情况：

<Terminal_control>{"cmd":"netstat -ano | findstr 4444","timeout":10}</Terminal_control>
\`\`\`
收到结果后继续分析...
`.trim();

